import test from 'node:test';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import {HEAD,INLINE_HEAD,PUBLISHER_SCRIPT,PUBLISHER_FILE,completeTracking,IDS} from '../scripts/publisher-tracking.mjs';
const script=PUBLISHER_SCRIPT;
function run(hostname,existingBeacon=false){const requests=[],context={location:{hostname,origin:'https://'+hostname,pathname:'/tool/',search:'?query=PRIVATE_INPUT',hash:'#PRIVATE_INPUT'},Date,document:{readyState:'complete',referrer:'https://example.com/?token=PRIVATE_INPUT',querySelector:()=>existingBeacon?{}:null,createElement:()=>({setAttribute(k,v){this[k]=v;}}),head:{appendChild:s=>requests.push(s)}}};context.window=context;vm.runInNewContext(script,context);return {requests,context};}
test('publisher requests are disabled on local and unapproved test hosts',()=>{for(const host of ['localhost','127.0.0.1','::1','preview.invalid'])assert.equal(run(host).requests.length,0);});
test('all four integrations initialize on production without URL input values',()=>{const {requests,context}=run('nanalab.kr');assert.equal(requests.length,4);for(const id of Object.values(IDS))assert.ok(script.includes(id));assert.ok(!JSON.stringify(context.dataLayer).includes('PRIVATE_INPUT'));assert.equal(requests.find(x=>x.src.includes('cloudflare')).src,'https://static.cloudflareinsights.com/beacon.min.js');});
test('existing edge beacon is reused and HTML injection is idempotent',()=>{assert.equal(run('nanalab.kr',true).requests.length,3);const once=completeTracking('<html><head></head><body>App</body></html>');assert.equal(completeTracking(once),once);assert.ok(once.includes('googletagmanager.com/ns.html'));});


test('shared publisher asset preserves exact legacy bytes and parser-blocking execution',()=>{
 assert.equal(PUBLISHER_SCRIPT,INLINE_HEAD.match(/<script>([\s\S]*?)<\/script>/)[1]);
 assert.ok(HEAD.includes('<script src="/trump-says/'+PUBLISHER_FILE+'"></script>'));
 assert.ok(!/\b(?:async|defer|type)=?/.test(HEAD));
 const legacy='<html><head>'+INLINE_HEAD+'</head><body>Kept body</body></html>';
 assert.equal(completeTracking(legacy),legacy.replace(INLINE_HEAD,HEAD));
 assert.equal(completeTracking(completeTracking(legacy)),completeTracking(legacy));
});

test('shared asset matches generated bytes and each example page loads it once',async()=>{
 const fs=await import('node:fs');
 assert.equal(fs.readFileSync(new URL('../docs/'+PUBLISHER_FILE,import.meta.url),'utf8'),PUBLISHER_SCRIPT);
 for(const name of ['index.html','search.html','sources.html','archive-menu.html','archive/2026-11.html','archive/2026-11-09.html','feed/latest-0001.html','posts/truth-117589581287691662.html']){
  const html=fs.readFileSync(new URL('../docs/'+name,import.meta.url),'utf8');
  assert.equal(html.split(HEAD).length-1,1,name);
  assert.ok(!html.includes(INLINE_HEAD),name);
  assert.ok(html.includes('googletagmanager.com/ns.html?id='+IDS.gtm),name);
 }
});

test('beacon waits for DOM readiness and does not duplicate an existing edge beacon',()=>{
 const callbacks=[],requests=[];
 const context={location:{hostname:'nanalab.kr',origin:'https://nanalab.kr',pathname:'/trump-says/'},Date,
 document:{readyState:'loading',referrer:'',querySelector:()=>({}),addEventListener:(event,callback,options)=>callbacks.push({event,callback,options}),createElement:()=>({setAttribute(k,v){this[k]=v;}}),head:{appendChild:s=>requests.push(s)}}};
 context.window=context;vm.runInNewContext(script,context);
 assert.equal(requests.length,3);assert.equal(callbacks[0].event,'DOMContentLoaded');assert.equal(callbacks[0].options.once,true);
 callbacks[0].callback();assert.equal(requests.length,3);
});
